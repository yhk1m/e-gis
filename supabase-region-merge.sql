-- e-GIS 회원 지역값 통합: '전남' · '광주' → '전남광주'
-- Supabase SQL Editor 에서 실행하세요. 여러 번 실행해도 안전합니다(두 번째부터는 0건).
--
-- 마이페이지의 지역 목록에서 '전남'과 '광주'를 '전남광주' 하나로 합쳤습니다.
-- 이미 저장된 회원 값도 함께 옮겨야 학교 통계·회원 목록에서 갈라져 보이지 않습니다.

-- ============================================================
-- 1) 바꾸기 전 확인 — 몇 명이 대상인지 먼저 봅니다
-- ============================================================
SELECT region, COUNT(*) AS 회원수
FROM public.user_profiles
WHERE region IN ('전남', '광주', '전남광주')
GROUP BY region
ORDER BY region;

-- ============================================================
-- 2) 실제 변경
--    바뀐 행 수가 결과로 나옵니다.
-- ============================================================
UPDATE public.user_profiles
SET region = '전남광주',
    updated_at = NOW()
WHERE region IN ('전남', '광주');

-- ============================================================
-- 3) 바꾼 뒤 확인 — '전남'/'광주'가 0건이어야 합니다
-- ============================================================
SELECT region, COUNT(*) AS 회원수
FROM public.user_profiles
WHERE region IN ('전남', '광주', '전남광주')
GROUP BY region
ORDER BY region;

